// Encodes the committed P2 withdraw vk + proof + public signals into the Soroban
// BLS12-381 byte layout and emits zk/verifier/src/withdraw_fixture.rs, so the P3
// contract test can verify the REAL proof (P2<->P3 integration). Also emits the
// deposit commitment (from the known demo note) so the test can rebuild the tree.
// Usage: node zk/scripts/gen-withdraw-soroban-fixture.mjs [c0c1|c1c0]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { commitmentHash, toField } from "../../lib/pool/mimc.ts";

const here = dirname(fileURLToPath(import.meta.url));
const order = process.argv[2] === "c1c0" ? "c1c0" : "c0c1";
const A = (f) => JSON.parse(readFileSync(resolve(here, "../artifacts/", f), "utf8"));
const vk = A("withdraw_vk.json");
const proof = A("withdraw_proof.json");
const pub = A("withdraw_public.json");

const P = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaabn; // Fp
const feBytes = (dec, width = 48) => {
  let v = ((BigInt(dec) % P) + P) % P;
  return Buffer.from(v.toString(16).padStart(width * 2, "0"), "hex");
};
const frBytes = (dec) => Buffer.from(BigInt(dec).toString(16).padStart(64, "0"), "hex");
const g1 = (p) => Buffer.concat([feBytes(p[0]), feBytes(p[1])]);
const g2 = (p) => {
  const x = order === "c0c1" ? [p[0][0], p[0][1]] : [p[0][1], p[0][0]];
  const y = order === "c0c1" ? [p[1][0], p[1][1]] : [p[1][1], p[1][0]];
  return Buffer.concat([feBytes(x[0]), feBytes(x[1]), feBytes(y[0]), feBytes(y[1])]);
};
const negG1 = (p) => g1([p[0], ((P - (BigInt(p[1]) % P)) % P).toString()]);

const rustBytes = (buf) => `[${[...buf].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ")}]`;
const arrOf = (name, n, buf) => `pub const ${name}: [u8; ${n}] = ${rustBytes(buf)};`;

// Demo note from zk/scripts/withdraw-prove.mjs (secret, nullifier, amount).
const commitment = commitmentHash(111111n, 222222n, 1234560000n);
const commitBuf = Buffer.from(toField(commitment).toString(16).padStart(64, "0"), "hex");

const icLines = vk.IC.map((p, i) => `    ${rustBytes(g1(p))}`).join(",\n");

const rs = `// AUTO-GENERATED by zk/scripts/gen-withdraw-soroban-fixture.mjs (Fp2 order=${order}).
// Real P2 withdraw proof + vk in Soroban BLS12-381 byte layout, for the P3
// integration test. DO NOT EDIT BY HAND. Regenerate from zk/artifacts/.
#![cfg(test)]

${arrOf("VK_ALPHA", 96, g1(vk.vk_alpha_1))}
${arrOf("VK_BETA", 192, g2(vk.vk_beta_2))}
${arrOf("VK_GAMMA", 192, g2(vk.vk_gamma_2))}
${arrOf("VK_DELTA", 192, g2(vk.vk_delta_2))}
pub const VK_IC: [[u8; 96]; ${vk.IC.length}] = [
${icLines}
];
${arrOf("PROOF_NEG_A", 96, negG1(proof.pi_a))}
${arrOf("PROOF_B", 192, g2(proof.pi_b))}
${arrOf("PROOF_C", 96, g1(proof.pi_c))}
${arrOf("PUB_ROOT", 32, frBytes(pub[0]))}
${arrOf("PUB_NULLIFIER", 32, frBytes(pub[1]))}
${arrOf("PUB_RECIPIENT", 32, frBytes(pub[2]))}
${arrOf("COMMITMENT", 32, commitBuf)}
pub const AMOUNT: i128 = ${BigInt(pub[3])};
`;

writeFileSync(resolve(here, "../verifier/src/withdraw_fixture.rs"), rs);
console.log("wrote withdraw_fixture.rs (order=" + order + ", amount=" + pub[3] + ")");
